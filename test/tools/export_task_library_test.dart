// Generates tools/task_library_seed.sql — the shared task library for the
// live server (2026-10-16), built from the app's OWN seeding code in a
// fresh in-memory database, so server ids match exactly what a fresh
// device seeds locally (the backend repositories still delegate some
// lookups — presets, equipment tags — to the local seed by id).
//
// Run: flutter test test/tools/export_task_library_test.dart --dart-define=SEED_DEMO_DATA=false
// Doubles as a check that the reference library is complete.
import 'dart:io';

import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:venurite/core/storage/app_database.dart';

String _q(Object? v) {
  if (v == null) return 'null';
  if (v is bool) return v ? 'true' : 'false';
  if (v is num) return v.toString();
  if (v is DateTime) return "'${v.toUtc().toIso8601String()}'";
  return "'${v.toString().replaceAll("'", "''")}'";
}

void main() {
  test('export shared task library as SQL', () async {
    final db = AppDatabase.forTesting(NativeDatabase.memory());
    await db.select(db.organisations).get(); // triggers seeding

    final venueTypes = await db.select(db.venueTypes).get();
    final equipmentTypes = await db.select(db.equipmentTypes).get();
    final allTemplates = await db.select(db.taskTemplates).get();
    final previousIds = allTemplates
        .map((t) => t.previousVersionId)
        .whereType<int>()
        .toSet();
    final current = allTemplates
        .where((t) => !previousIds.contains(t.id))
        .toList();
    final ttvt = await db.select(db.taskTemplateVenueTypes).get();
    final etvt = await db.select(db.equipmentTypeVenueTypes).get();

    expect(venueTypes.length, greaterThanOrEqualTo(12));
    expect(equipmentTypes.length, greaterThan(50));
    expect(current.length, greaterThan(200));

    final b = StringBuffer()
      ..writeln('-- GENERATED by test/tools/export_task_library_test.dart — do not edit by hand.')
      ..writeln('-- Shared task library (organisation_id null). Ids match a fresh local seed.')
      ..writeln('begin;');
    for (final v in venueTypes) {
      b.writeln(
        'insert into venue_types (id, name, organisation_id) values '
        '(${v.id}, ${_q(v.name)}, null) on conflict (id) do update set name = excluded.name;',
      );
    }
    for (final e in equipmentTypes) {
      b.writeln(
        'insert into equipment_types (id, name, organisation_id) values '
        '(${e.id}, ${_q(e.name)}, null) on conflict (id) do update set name = excluded.name;',
      );
    }
    for (final t in current) {
      b.writeln(
        'insert into task_templates (id, template_group_id, version_number, previous_version_id, '
        'title, segment, applicable_role_tiers, method, requires_photo, requires_notes, '
        'custom_fields_json, min_limit, max_limit, unit, legal_limit_category, is_critical, '
        'requires_corrective_action_on_fail, fix_instructions, equipment_type_id, created_at, '
        'created_by_user_id, priority, job_role, guidance_text, requires_supplier_selection, '
        'organisation_id, extra_fields_json, random_photo_check_enabled) values ('
        '${t.id}, ${t.templateGroupId}, ${t.versionNumber}, null, ${_q(t.title)}, ${_q(t.segment)}, '
        '${_q(t.applicableRoleTiers)}, ${_q(t.method)}, ${_q(t.requiresPhoto)}, ${_q(t.requiresNotes)}, '
        '${_q(t.customFieldsJson)}, ${_q(t.minLimit)}, ${_q(t.maxLimit)}, ${_q(t.unit)}, '
        '${_q(t.legalLimitCategory)}, ${_q(t.isCritical)}, ${_q(t.requiresCorrectiveActionOnFail)}, '
        '${_q(t.fixInstructions)}, ${_q(t.equipmentTypeId)}, ${_q(t.createdAt)}, null, '
        '${_q(t.priority)}, ${_q(t.jobRole)}, ${_q(t.guidanceText)}, ${_q(t.requiresSupplierSelection)}, '
        'null, ${_q(t.extraFieldsJson)}, ${_q(t.randomPhotoCheckEnabled)}) on conflict (id) do nothing;',
      );
    }
    for (final j in ttvt) {
      b.writeln(
        'insert into task_template_venue_types (task_template_group_id, venue_type_id) values '
        '(${j.taskTemplateGroupId}, ${j.venueTypeId}) on conflict do nothing;',
      );
    }
    for (final j in etvt) {
      b.writeln(
        'insert into equipment_type_venue_types (equipment_type_id, venue_type_id) values '
        '(${j.equipmentTypeId}, ${j.venueTypeId}) on conflict do nothing;',
      );
    }
    b
      ..writeln("select setval('venue_types_id_seq', greatest((select max(id) from venue_types), 1000));")
      ..writeln("select setval('equipment_types_id_seq', greatest((select max(id) from equipment_types), 1000));")
      ..writeln("select setval('task_templates_id_seq', greatest((select max(id) from task_templates), 10000));")
      ..writeln('commit;');

    File('tools/task_library_seed.sql').writeAsStringSync(b.toString());
    // ignore: avoid_print
    print(
      'venue types ${venueTypes.length}, equipment types ${equipmentTypes.length}, '
      'templates ${current.length}, template tags ${ttvt.length}, equipment tags ${etvt.length}',
    );
    await db.close();
  });
}
